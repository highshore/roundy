assert.equal(at(24, balanced, { lockdown_minutes: 24 * 60 }).kind, 'imminent');
assert.equal(at(1, balanced, { lockdown_minutes: 0 }).kind, 'available');
assert.equal(at(250, balanced, { lockdown_minutes: 300 * 60 }).kind, 'imminent');

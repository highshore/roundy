import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const load = async path => import('data:text/javascript;base64,' + Buffer.from(ts.transpileModule(await readFile(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText).toString('base64'));
const { eventStatus, countdownParts } = await load('src/lib/event-status.ts');
const { headingText } = await load('src/lib/heading.ts');
const start = Date.parse('2026-11-01T10:00:00Z'), hour = 3_600_000;
const event = { starts_at: new Date(start).toISOString(), ends_at: new Date(start + 2 * hour).toISOString(), capacity: 20, seats_remaining: 10, status: 'live' };
const balanced = { total: 10, women_count: 5, men_count: 5 };
const at = (hours, counts = balanced, changes = {}) => eventStatus({ ...event, ...changes }, counts, start - hours * hour);
assert.equal(at(241).kind, 'early');
assert.equal(at(240).kind, 'early'); // Checkout is inclusive at the cutoff.
assert.equal(at(240).deadline, start - 240 * hour);
assert.equal(at(240 - 1 / hour).kind, 'available');
assert.equal(at(72 + 1 / hour).kind, 'available');
assert.equal(at(72).kind, 'imminent');
assert.equal(at(72).deadline, start);
assert.equal(at(1).kind, 'imminent');
assert.equal(at(0).kind, 'started');
assert.equal(at(-2).kind, 'ended');
assert.equal(at(100, { total: 14, women_count: 7, men_count: 7 }, { seats_remaining: 6 }).kind, 'available');
assert.equal(at(100, { total: 15, women_count: 8, men_count: 7 }, { seats_remaining: 5 }).kind, 'almost-full');
assert.equal(at(72, { total: 10, women_count: 6, men_count: 4 }).discount, 'gents');
assert.equal(at(100, { total: 10, women_count: 6, men_count: 4 }).discount, null);
assert.equal(at(72, { total: 10, women_count: 4, men_count: 6 }).discount, 'ladies');
assert.equal(at(100, { total: 9, women_count: 5, men_count: 4 }).discount, null);
assert.deepEqual(at(100, { total: 16, women_count: 10, men_count: 6 }, { seats_remaining: 4 }), { kind: 'almost-full', deadline: null, discount: null });
for (const hours of [241, 100, 0, -2]) assert.equal(at(hours, { total: 10, women_count: 7, men_count: 3 }).discount, null);
assert.equal(at(300, balanced, { seats_remaining: 0 }).kind, 'full');
assert.equal(at(300, balanced, { status: 'cancelled' }).kind, 'closed');
assert.equal(at(300, balanced, { capacity: 0 }).kind, 'full');
assert.equal(at(100, balanced, { early_bird_hours: 96 }).kind, 'available');
assert.equal(at(80, balanced, { lockdown_minutes: 90 * 60 }).kind, 'imminent');
assert.equal(eventStatus(event, undefined, start - 100 * hour).discount, null);
assert.deepEqual(countdownParts(start + 90061000, start), { days: 1, hours: 1, minutes: 1, seconds: 1 });
assert.deepEqual(countdownParts(start - 1, start), { days: 0, hours: 0, minutes: 0, seconds: 0 });
assert.equal(headingText('Your matches.'), 'Your Matches');
assert.equal(headingText('Meet 1:1 with Roundy and PayApp!'), 'Meet 1:1 with Roundy and PayApp');
assert.equal(headingText('MBTI and SMS'), 'MBTI and SMS');
assert.equal(headingText('새로운 매칭.'), '새로운 매칭');
console.log('PASS event-status cutoffs, countdowns, occupancy, gender offers, terminal states, custom pricing windows and heading casing');

